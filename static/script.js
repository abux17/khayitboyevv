// ================================
// LANGUAGE
// ================================

function applyLanguage(language) {
  const selectedLanguage = translations[language] ? language : "uz";
  document.documentElement.lang = selectedLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const translatedText = translations[selectedLanguage][key];

    if (typeof translatedText === "string") {
      element.textContent = translatedText;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    const translatedText = translations[selectedLanguage][key];

    if (typeof translatedText === "string") {
      element.placeholder = translatedText;
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    const translatedText = translations[selectedLanguage][key];

    if (typeof translatedText === "string") {
      element.alt = translatedText;
    }
  });

  const languageSelector = document.querySelector(
    "#language, #languageSelect, #language-selector, [data-language-select]"
  );

  if (languageSelector) {
    languageSelector.value = selectedLanguage;
  }

  try {
    localStorage.setItem("portfolio-language", selectedLanguage);
  } catch (error) {
    console.warn("Til sozlamasini saqlab bo‘lmadi:", error);
  }
}


// ================================
// THEME
// ================================

function applyTheme(theme) {
  const isLight = theme === "light";

  document.body.classList.toggle("light-theme", isLight);

  const themeButton = document.querySelector(
    "#themeToggle, #theme-toggle, [data-theme-toggle]"
  );

  if (themeButton) {
    themeButton.setAttribute("aria-pressed", String(isLight));

    const icon = themeButton.querySelector("i, svg, .icon");

    if (icon && icon.tagName === "I") {
      icon.classList.toggle("icon-sun", isLight);
      icon.classList.toggle("icon-moon", !isLight);
    }

    themeButton.setAttribute(
      "aria-label",
      isLight ? "Qorong‘i mavzuga o‘tish" : "Yorug‘ mavzuga o‘tish"
    );
  }

  try {
    localStorage.setItem("portfolio-theme", theme);
  } catch (error) {
    console.warn("Mavzu sozlamasini saqlab bo‘lmadi:", error);
  }
}


