// INITIALIZATION
// ================================

document.addEventListener("DOMContentLoaded", () => {
  const languageSelector = document.querySelector(
    "#language, #languageSelect, #language-selector, [data-language-select]"
  );

  let savedLanguage = "uz";
  let savedTheme = "dark";

  try {
    savedLanguage =
      localStorage.getItem("portfolio-language") || "uz";

    savedTheme =
      localStorage.getItem("portfolio-theme") || "dark";
  } catch (error) {
    console.warn("Saqlangan sozlamalarni o‘qib bo‘lmadi:", error);
  }

  applyLanguage(savedLanguage);
  applyTheme(savedTheme);

  if (languageSelector) {
    languageSelector.addEventListener("change", (event) => {
      applyLanguage(event.target.value);
    });
  }

  const themeButton = document.querySelector(
    "#themeToggle, #theme-toggle, [data-theme-toggle]"
  );

  if (themeButton) {
    themeButton.addEventListener("click", () => {
      const isLight = document.body.classList.contains("light-theme");
      applyTheme(isLight ? "dark" : "light");
    });
  }

  initializeMobileMenu();
  initializeGallery();
  initializeSocialLinks();

  const yearElement = document.querySelector("#year");

  if (yearElement) {
    yearElement.textContent = new Date().getFullYear();
  }
});
