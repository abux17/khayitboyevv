// MOBILE MENU
// ================================

function initializeMobileMenu() {
  const menuButton = document.querySelector(
    "#menuToggle, #menu-toggle, .menu-toggle, [data-menu-toggle]"
  );

  const navigation = document.querySelector(
    "#navLinks, #nav-links, .nav-links, [data-nav-links]"
  );

  if (!menuButton || !navigation) return;

  menuButton.addEventListener("click", () => {
    const isOpen = navigation.classList.toggle("open");

    menuButton.setAttribute("aria-expanded", String(isOpen));
    menuButton.setAttribute(
      "aria-label",
      isOpen ? "Menyuni yopish" : "Menyuni ochish"
    );
  });

  navigation.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      navigation.classList.remove("open");
      menuButton.setAttribute("aria-expanded", "false");
    });
  });

  document.addEventListener("click", (event) => {
    if (
      !navigation.contains(event.target) &&
      !menuButton.contains(event.target)
    ) {
      navigation.classList.remove("open");
      menuButton.setAttribute("aria-expanded", "false");
    }
  });
}


// ================================
// PHOTO GALLERY / LIGHTBOX
// ================================

function initializeGallery() {
  const photoButtons = Array.from(
    document.querySelectorAll(".gallery-item[data-photo], [data-photo]")
  );

  const lightbox = document.getElementById("lightbox");

  if (!photoButtons.length || !lightbox) return;

  const lightboxImage = document.getElementById("lightboxImage");
  const lightboxCaption = document.getElementById("lightboxCaption");
  const closeButton = document.getElementById("lightboxClose");

  // HTML dagi haqiqiy ID lar:
  const previousButton = document.getElementById("prevPhoto");
  const nextButton = document.getElementById("nextPhoto");

  if (!lightboxImage) return;

  let currentIndex = 0;
  let previousFocus = null;

  function getPhoto(index) {
    const button = photoButtons[index];
    if (!button) return null;

    const image = button.querySelector("img");
    if (!image) return null;

    return {
      src: image.currentSrc || image.src,
      alt: image.alt || `Photo ${index + 1}`
    };
  }

  function openLightbox(index) {
    const photo = getPhoto(index);
    if (!photo || !photo.src) return;

    currentIndex = index;
    previousFocus = document.activeElement;

    lightboxImage.src = photo.src;
    lightboxImage.alt = photo.alt;

    if (lightboxCaption) {
      lightboxCaption.textContent = photo.alt;
    }

    // ASOSIY TUZATISH: hidden atributini olib tashlash
    lightbox.hidden = false;
    lightbox.removeAttribute("hidden");

    lightbox.classList.add("open");
    lightbox.setAttribute("aria-hidden", "false");
    document.body.classList.add("lightbox-open");

    if (closeButton) {
      closeButton.focus();
    }
  }

  function closeLightbox() {
    lightbox.classList.remove("open");
    lightbox.hidden = true;
    lightbox.setAttribute("aria-hidden", "true");
    document.body.classList.remove("lightbox-open");

    lightboxImage.removeAttribute("src");

    if (previousFocus && typeof previousFocus.focus === "function") {
      previousFocus.focus();
    }
  }

  function showPhoto(direction) {
    currentIndex =
      (currentIndex + direction + photoButtons.length) %
      photoButtons.length;

    openLightbox(currentIndex);
  }

  // Suratlarni ochish
  photoButtons.forEach((button, index) => {
    button.addEventListener("click", (event) => {
      event.preventDefault();
      openLightbox(index);
    });
  });

  // Yopish tugmasi
  if (closeButton) {
    closeButton.addEventListener("click", closeLightbox);
  }

  // Oldingi va keyingi surat
  if (previousButton) {
    previousButton.addEventListener("click", (event) => {
      event.stopPropagation();
      showPhoto(-1);
    });
  }

  if (nextButton) {
    nextButton.addEventListener("click", (event) => {
      event.stopPropagation();
      showPhoto(1);
    });
  }

  // Orqa fon ustiga bosilganda yopish
  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) {
      closeLightbox();
    }
  });

  // Klaviatura boshqaruvi
  document.addEventListener("keydown", (event) => {
    if (lightbox.hidden) return;

    if (event.key === "Escape") {
      closeLightbox();
    } else if (event.key === "ArrowLeft") {
      showPhoto(-1);
    } else if (event.key === "ArrowRight") {
      showPhoto(1);
    }
  });

  // Rasm yuklanmasa xabar ko‘rsatish
  lightboxImage.addEventListener("error", () => {
    lightboxImage.alt = "Bu suratni yuklab bo‘lmadi.";
  });
}


